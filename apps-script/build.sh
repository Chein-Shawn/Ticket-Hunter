#!/bin/bash
# Build a single-file bundle for copy-paste install: dist/TicketHunter.gs
# 打包成單一檔案，方便貼進 Apps Script 編輯器。
set -euo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$DIR/dist"
OUT="$DIR/dist/TicketHunter.gs"
{
  echo "/**"
  echo " * Ticket hunter — Google Apps Script bundle (generated by build.sh; do not edit by hand)."
  echo " * Source: apps-script/src/*.gs  ·  License: MIT"
  echo " * 安裝方式 / Install: see apps-script/SETUP.md"
  echo " */"
  for f in "$DIR"/src/*.gs; do
    echo
    echo "// ===== $(basename "$f") ====="
    cat "$f"
  done
} > "$OUT"
cp "$DIR/appsscript.json" "$DIR/dist/appsscript.json"
echo "Built $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes)"
